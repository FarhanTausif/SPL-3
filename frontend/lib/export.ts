/**
 * Export & Report Generation
 * Generate reports in JSON, CSV, and PDF formats
 */

export interface RunReport {
  runId: string;
  timestamp: string;
  prompt: string;
  language: string;
  status: string;
  halluckinationScore: number;
  verdict: string;
  generatedCode: string;
  evidence: Array<{
    kind: string;
    payload: Record<string, any>;
  }>;
  duration: number;
}

/**
 * Export run as JSON
 */
export function exportAsJSON(report: RunReport): void {
  const json = JSON.stringify(report, null, 2);
  downloadFile(json, `run-${report.runId}.json`, 'application/json');
}

/**
 * Export run as CSV (flattened)
 */
export function exportAsCSV(report: RunReport): void {
  const rows = [
    ['Field', 'Value'],
    ['Run ID', report.runId],
    ['Timestamp', report.timestamp],
    ['Language', report.language],
    ['Status', report.status],
    ['Hallucination Score', report.halluckinationScore.toFixed(2)],
    ['Verdict', report.verdict],
    ['Duration (ms)', report.duration.toString()],
    ['Prompt', report.prompt],
    ['Generated Code', report.generatedCode],
    [],
    ['Evidence Summary'],
    ...report.evidence.map((e) => [e.kind, JSON.stringify(e.payload)]),
  ];

  const csv = rows.map((row) => row.map((cell) => `"${cell.toString().replace(/"/g, '""')}"`).join(',')).join('\n');
  downloadFile(csv, `run-${report.runId}.csv`, 'text/csv');
}

/**
 * Export run as Markdown report
 */
export function exportAsMarkdown(report: RunReport): void {
  const md = `# DeHalu Verification Report

**Run ID:** ${report.runId}
**Timestamp:** ${report.timestamp}
**Duration:** ${report.duration}ms

## Summary

- **Language:** ${report.language}
- **Status:** ${report.status}
- **Hallucination Score:** ${(report.halluckinationScore * 100).toFixed(1)}%
- **Verdict:** ${report.verdict.toUpperCase()}

## Original Prompt

\`\`\`
${report.prompt}
\`\`\`

## Generated Code

\`\`\`${report.language.toLowerCase()}
${report.generatedCode}
\`\`\`

## Verification Evidence

${report.evidence
  .map(
    (e) => `### ${e.kind}

\`\`\`json
${JSON.stringify(e.payload, null, 2)}
\`\`\``
  )
  .join('\n\n')}

---

*Generated by DeHalu - AI Code Hallucination Detection System*
*${new Date().toISOString()}*
`;

  downloadFile(md, `run-${report.runId}.md`, 'text/markdown');
}

