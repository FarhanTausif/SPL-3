/**
 * Trigger PDF export (browser's print-to-PDF)
 */
export function exportAsPDF(report: RunReport): void {
  const html = generatePDFHTML(report);
  const newWindow = window.open('', '_blank');
  if (newWindow) {
    newWindow.document.write(html);
    newWindow.document.close();
    newWindow.print();
  }
}

/**
 * Export multiple reports as ZIP (requires jszip library)
 */
export function exportMultipleReports(reports: RunReport[], format: 'json' | 'csv' | 'md'): void {
  const lines = reports.map((report) => {
    switch (format) {
      case 'json':
        return JSON.stringify(report, null, 2);
      case 'csv':
        return formatReportAsCSV(report);
      case 'md':
        return formatReportAsMarkdown(report);
    }
  });

  const content = lines.join('\n\n---\n\n');
  const filename = `dehalu-reports-${new Date().toISOString().split('T')[0]}.${format === 'md' ? 'md' : format}`;
  downloadFile(content, filename, format === 'json' ? 'application/json' : 'text/plain');
}

// Helper functions

function downloadFile(content: string, filename: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType });
  const url = window.URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  window.URL.revokeObjectURL(url);
}

function formatReportAsCSV(report: RunReport): string {
  const rows = [
    ['Field', 'Value'],
    ['Run ID', report.runId],
    ['Timestamp', report.timestamp],
    ['Language', report.language],
    ['Status', report.status],
    ['Hallucination Score', report.halluckinationScore.toFixed(2)],
    ['Verdict', report.verdict],
    ['Duration (ms)', report.duration.toString()],
  ];

  return rows.map((row) => row.map((cell) => `"${cell.toString().replace(/"/g, '""')}"`).join(',')).join('\n');
}

function formatReportAsMarkdown(report: RunReport): string {
  return `# ${report.runId}

**Timestamp:** ${report.timestamp}
**Language:** ${report.language}
**Verdict:** ${report.verdict}
**Score:** ${(report.halluckinationScore * 100).toFixed(1)}%

\`\`\`
${report.prompt}
\`\`\`

\`\`\`${report.language.toLowerCase()}
${report.generatedCode}
\`\`\`
`;
}

function escapeHtml(text: string): string {
  const div = document.createElement('div');
  div.textContent = text;
  return div.innerHTML;
}
